"""Read the supplied public map selection on Actions; never change production data.

Uses ordinary Playwright navigation and observes responses generated by that
page. No direct API replay, request modification, credentials, or proxy setup.
Only structural response metadata and aggregate counts are written to artifacts.
"""
from __future__ import annotations

from collections import Counter
import json
import os
from pathlib import Path
import re
import sys
import time
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from monitor import now_kst, parse_raw_text, validate_snapshot  # noqa: E402


PANEL_SCRIPT = r"""(advance) => {
  const candidates = [...document.querySelectorAll('[class*="ScrollBox"][class*="scroller"]')];
  const panel = candidates.find(e => /매물\s*[\d,]+\s*개/.test(e.innerText));
  const text = panel ? panel.innerText : document.body.innerText;
  const m = panel && text.match(/매물\s*([\d,]+)\s*개/);
  const state = {
    panelFound: Boolean(panel), text,
    declaredCount: m ? Number(m[1].replaceAll(',', '')) : null,
    cardCount: (text.match(/(?:수성범어더블유|수성범어W)\s*\d+동/g) || []).length,
    sourceReady: Boolean(panel && /오피스텔/.test(text)),
    scrollTop: panel ? panel.scrollTop : 0,
    scrollHeight: panel ? panel.scrollHeight : 0,
    clientHeight: panel ? panel.clientHeight : 0,
    atBottom: Boolean(panel && panel.scrollTop + panel.clientHeight >= panel.scrollHeight - 8)
  };
  if (advance && panel) panel.scrollBy({top: panel.clientHeight * 12, behavior: 'instant'});
  return state;
}"""


def terminal_page(text):
    if re.search(r'비정상적인 접근|접근이 제한|서비스 이용이 제한|자동입력 방지|로봇이 아닙니다|verify you are human', text, re.I):
        return 'access-restricted'
    if re.search(r'페이지를 찾을 수 없|잘못된 주소이거나', text):
        return 'ordinary-not-found'
    return None


def structural_summary(payload):
    """Do not expose records, contact data, headers, cookies, or token values."""
    if isinstance(payload, list):
        return {'shape': 'list', 'length': len(payload)}
    if not isinstance(payload, dict):
        return {'shape': type(payload).__name__}
    result = {'shape': 'object', 'arrayLengths': {}, 'counts': {}}
    for key, value in payload.items():
        if isinstance(value, list):
            result['arrayLengths'][key] = len(value)
        if key in ('totalCount', 'totalArticleCount', 'count') and isinstance(value, int) and not isinstance(value, bool):
            result['counts'][key] = value
    return result


def run_probe(config):
    from playwright.sync_api import sync_playwright, TimeoutError as BrowserTimeout
    parsed = urlsplit(config['url'])
    if parsed.scheme != 'https' or parsed.netloc != 'fin.land.naver.com' or parsed.path != '/map':
        raise ValueError('Expected the supplied public HTTPS map URL')
    report = {'startedAt': now_kst(), 'scope': config['scope'],
              'fullComplexEligible': False, 'productionFilesChanged': False,
              'stage': 'starting', 'progress': [], 'apiResponses': [], 'failedDocuments': []}
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        context = browser.new_context(viewport={'width': 1280, 'height': 1000}, locale='ko-KR')
        page = context.new_page()
        page.set_default_timeout(10000)

        def observe_response(response):
            url = urlsplit(response.url)
            if url.hostname != 'fin.land.naver.com' or '/api/' not in url.path or len(report['apiResponses']) >= 30:
                return
            event = {'path': url.path, 'status': response.status}
            if response.status == 200 and 'json' in response.headers.get('content-type', ''):
                try:
                    event.update(structural_summary(response.json()))
                except Exception as exc:
                    event['parseErrorType'] = type(exc).__name__
            report['apiResponses'].append(event)

        def observe_failure(request):
            if request.resource_type == 'document':
                report['failedDocuments'].append({'path': urlsplit(request.url).path,
                                                  'error': request.failure})

        page.on('response', observe_response)
        page.on('requestfailed', observe_failure)
        try:
            started = time.monotonic()
            try:
                response = page.goto(config['url'], wait_until='commit', timeout=45000)
            except BrowserTimeout:
                report.update(stage='first-response-timeout', seconds=round(time.monotonic()-started, 2))
                return report
            report.update(documentStatus=response.status if response else None,
                          firstResponseSeconds=round(time.monotonic()-started, 2))
            if response and response.status in (401, 403, 429):
                report['stage'] = 'http-access-response'
                return report
            expected, previous_count, stalls, stable = None, -1, 0, 0
            for _ in range(45):
                page.wait_for_timeout(1200)
                state = page.evaluate(PANEL_SCRIPT, False)
                terminal = terminal_page(state['text'])
                if terminal:
                    report['stage'] = terminal
                    return report
                declared, items = parse_raw_text(state['text'])
                report['progress'].append({key: state[key] for key in (
                    'declaredCount', 'cardCount', 'scrollTop', 'scrollHeight', 'atBottom', 'panelFound')})
                report.update(declaredCount=declared, cardCount=state['cardCount'], parsedCount=len(items))
                if declared and declared > 0:
                    if expected is not None and expected != declared:
                        report['stage'] = 'declared-count-changed'
                        return report
                    expected = declared
                complete = state['sourceReady'] and expected and declared == expected == len(items) == state['cardCount']
                stable = stable + 1 if complete else 0
                if stable >= 2:
                    quality = validate_snapshot({'date': now_kst()[:10], 'declaredCount': expected, 'items': items},
                                                require_complete=True, allowed_dongs=['101동','102동','103동','105동'])
                    report.update(stage='map-scope-complete', validation=quality,
                                  buildings=dict(Counter(x['dong'] for x in items)), stableReads=stable)
                    return report
                stalls = stalls + 1 if state['atBottom'] and len(items) == previous_count and items else 0
                if stalls >= 5:
                    report['stage'] = 'incomplete-at-bottom'
                    return report
                previous_count = len(items)
                if state['panelFound'] and state['sourceReady'] and not complete:
                    page.evaluate(PANEL_SCRIPT, True)
            report['stage'] = 'loading-or-scroll-limit'
            return report
        finally:
            context.close()
            browser.close()


def main():
    config = json.loads((ROOT/'config/map-probe.json').read_text())
    try:
        report = run_probe(config)
    except Exception as exc:
        report = {'stage': 'probe-error', 'errorType': type(exc).__name__,
                  'fullComplexEligible': False, 'productionFilesChanged': False}
    report['finishedAt'] = now_kst()
    directory = ROOT/'probe-results'
    directory.mkdir(exist_ok=True)
    (directory/'map-probe.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n')
    print(json.dumps(report, ensure_ascii=False, indent=2), flush=True)
    if summary := os.environ.get('GITHUB_STEP_SUMMARY'):
        with open(summary, 'a') as handle:
            handle.write('## 지도 URL 수집 시험\n\n')
            handle.write('지도 선택 범위의 수집 가능성만 검사합니다. 단지 전체 자료로 저장하지 않습니다.\n\n```json\n')
            handle.write(json.dumps(report, ensure_ascii=False, indent=2)+'\n```\n')
    return 0 if report['stage'] == 'map-scope-complete' else 1


if __name__ == '__main__':
    raise SystemExit(main())
